import {test,expect} from '@playwright/test'
import {seed,swipe,readRecords} from './helpers'

test('設定画面で距離だけを選んだエアロバイクを割り当て、時間なしで保存・同日更新できる',async({page})=>{
  await seed(page)
  await page.getByLabel('店舗を選択').selectOption('__settings__')
  await page.getByRole('button',{name:'種目の管理',exact:true}).tap()
  await page.getByLabel('種目名',{exact:true}).fill('エアロバイク')
  await page.getByLabel('種目の種類').selectOption('cardio')
  await page.getByLabel('走行距離 (km)',{exact:true}).check()
  await page.getByRole('button',{name:'＋ 種目を登録'}).tap()
  await expect(page.getByRole('heading',{name:'エアロバイク',exact:true})).toBeVisible()
  await page.locator('.app').evaluate(el=>el.scrollTop=0)
  await swipe(page)
  await page.getByRole('button',{name:'店舗設定',exact:true}).tap()
  await page.getByRole('combobox',{name:'共通の種目',exact:true}).selectOption({label:'エアロバイク'})
  await page.getByRole('button',{name:'店舗に種目を登録'}).tap()
  await expect(page.locator('article').filter({has:page.getByRole('heading',{name:'エアロバイク',exact:true})})).toBeVisible()
  await page.getByLabel('店舗を選択').selectOption('a')
  await page.getByRole('button',{name:'エアロバイク',exact:true}).tap()
  await expect(page.getByLabel('運動時間 (分)')).toHaveCount(0)
  await expect(page.getByLabel('傾斜 (%)')).toHaveCount(0)
  await expect(page.getByLabel('走行距離 (km)')).toHaveValue('')
  await page.getByLabel('走行距離 (km)').fill('3.25')
  await page.getByRole('button',{name:'＋ 記録を保存'}).tap()
  await expect.poll(()=>readRecords(page)).toHaveLength(1)
  const id=(await readRecords(page))[0].id
  await expect(page.getByLabel('走行距離 (km)')).toHaveValue('3.25')
  await page.getByLabel('走行距離 (km)').fill('4.5')
  await page.getByRole('button',{name:'＋ 記録を保存'}).tap()
  await expect(page.getByText('前回の記録：4.5km')).toBeVisible()
  const records=await readRecords(page)
  expect(records).toHaveLength(1)
  expect(records[0]).toMatchObject({id,kind:'cardio',metrics:{distance:4.5}})
  expect(records[0]).not.toHaveProperty('minutes')
  await expect(page.getByLabel('走行距離 (km)')).toHaveValue('4.5')
  await expect(page.getByRole('region',{name:'成長グラフ'}).getByText('走行距離（km）')).toBeVisible()
  await expect(page.getByRole('region',{name:'成長グラフ'}).getByRole('button',{name:'1回目 4.5 km'})).toBeVisible()
  expect(await page.locator('.app').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
})
